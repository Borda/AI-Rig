"""Exercise the protected runners with pytest's real JUnit reporter."""

from __future__ import annotations

import os
import shlex
import subprocess
import sys
import sysconfig
from pathlib import Path
from xml.etree import ElementTree

import pytest

SHARED = Path(__file__).resolve().parents[2] / "shared"


@pytest.fixture
def project(tmp_path: Path) -> Path:
    """Prepare a configured JUnit report, existing checkout evidence and a test with captured output."""
    (tmp_path / "results").mkdir()
    (tmp_path / "results/report.xml").write_text("prior report", encoding="utf-8")
    (tmp_path / "pytest.ini").write_text(
        "[pytest]\naddopts = --junitxml=results/report.xml\njunit_suite_name = project\njunit_logging = system-out\n",
        encoding="utf-8",
    )
    (tmp_path / "test_sample.py").write_text("def test_result(): print('captured result')\n", encoding="utf-8")
    return tmp_path


def _assert_report(path: Path) -> None:
    """Check the reporter retained its configured metadata, test result and captured output."""
    suite = ElementTree.parse(path).getroot().find("testsuite")  # noqa: S314 - generated by the fixture
    assert suite is not None
    assert suite.get("name") == "project"
    assert suite.get("tests") == "1"
    case = suite.find("testcase")
    assert case is not None
    assert case.get("name") == "test_result"
    assert "captured result" in case.findtext("system-out", default="")


@pytest.mark.integration
@pytest.mark.installed_plugin
@pytest.mark.parametrize(
    ("options", "report"),
    [
        pytest.param(["-p", "xdist.plugin", "-n", "1"], "junit.xml", id="project-ini-xdist"),
        pytest.param(
            ["-p", "no:xdist", "--junit-xml", "${CODEX_RIG_PYTEST_ARTIFACTS}/custom report.xml"],
            "custom report.xml",
            id="run-local-cli-override",
        ),
    ],
)
def test_targeted_pytest_preserves_junit_results(project: Path, options: list[str], report: str) -> None:
    """Targeted tests retain JUnit contents in run evidence while preserving the checkout's report."""
    run = project / "run with spaces"
    result = subprocess.run(
        [
            sys.executable,
            "-I",
            str(SHARED / "run_targeted_pytest.py"),
            "--checkout",
            str(project),
            str(run),
            "--",
            sys.executable,
            "-m",
            "pytest",
            *options,
        ],
        env=os.environ | {"PYTEST_DISABLE_PLUGIN_AUTOLOAD": "1", "PYTEST_ADDOPTS": ""},
        capture_output=True,
        text=True,
        check=False,
    )
    assert result.returncode == 0, result.stdout + result.stderr
    assert (project / "results/report.xml").read_text(encoding="utf-8") == "prior report"
    _assert_report(run / report)


@pytest.mark.integration
@pytest.mark.installed_plugin
def test_gate_keeps_project_junit_report_in_checks(project: Path) -> None:
    """The ordinary gate retains its JUnit report beside gate outputs and preserves the existing report."""
    executable = "& '" + sys.executable.replace("'", "''") + "'" if os.name == "nt" else shlex.quote(sys.executable)
    skips = [part for gate in ("lint", "format", "types", "review") for part in (f"--skip-{gate}", "out of scope")]
    run = project / "run"
    result = subprocess.run(
        [
            sys.executable,
            str(SHARED / "run_gates.py"),
            "--out",
            str(run),
            "--tests",
            f"{executable} -m pytest -p no:xdist",
            *skips,
        ],
        cwd=project,
        env=os.environ | {"PYTEST_DISABLE_PLUGIN_AUTOLOAD": "1", "PYTEST_ADDOPTS": ""},
        capture_output=True,
        text=True,
        check=False,
    )
    assert result.returncode == 0, result.stdout + result.stderr
    assert (project / "results/report.xml").read_text(encoding="utf-8") == "prior report"
    _assert_report(run / "checks/junit.xml")


@pytest.mark.integration
@pytest.mark.installed_plugin
@pytest.mark.parametrize(
    "clear_path", [pytest.param(False, id="inherited-path"), pytest.param(True, id="cleared-path")]
)
@pytest.mark.parametrize(
    "parent_report", [pytest.param(True, id="parent-junit"), pytest.param(False, id="child-only-junit")]
)
def test_direct_pytest_children_preserve_distinct_reports_and_project_options(
    project: Path, clear_path: bool, parent_report: bool
) -> None:
    """Sequential direct children keep their own selected results and cannot overwrite a checkout report."""
    child = project / "child"
    helpers = child / "helpers"
    helpers.mkdir(parents=True)
    (helpers / "project_plugin.py").write_text(
        "def pytest_addoption(parser): parser.addoption('--child-flag')\n", encoding="utf-8"
    )
    (child / "pytest.ini").write_text(
        "[pytest]\npythonpath = helpers\naddopts = -p project_plugin --child-flag yes --junitxml=existing.xml\n",
        encoding="utf-8",
    )
    (child / "existing.xml").write_text("previous child report", encoding="utf-8")
    (child / "explicit.xml").write_text("previous CLI report", encoding="utf-8")
    (child / "test_child.py").write_text(
        "import os, sys\n"
        "def test_first(pytestconfig):\n"
        "    assert pytestconfig.getoption('--child-flag') == 'yes'\n"
        "    assert (os.environ['PARENT_PATH'] in sys.path) == (os.environ['CLEAR_CHILD_PATH'] == 'no')\n"
        "def test_second(): pass\n"
        "def test_stock(pytestconfig):\n"
        "    assert not pytestconfig.pluginmanager.hasplugin('codex_rig_pytest_artifacts')\n"
        "    assert ('PYTHONPATH' in os.environ) == (os.environ['CLEAR_CHILD_PATH'] == 'no')\n"
        "    assert 'CODEX_RIG_PYTEST_ARTIFACTS' not in os.environ\n"
        "def test_explicit_failure(): assert False, 'child failure'\n",
        encoding="utf-8",
    )
    (project / "test_outer.py").write_text(
        "import os, shutil, subprocess, sys\n"
        "def test_outer():\n"
        "    env = os.environ.copy()\n"
        "    if os.environ['CLEAR_CHILD_PATH'] == 'yes': env.pop('PYTHONPATH', None)\n"
        "    command = [sys.executable, '-m', 'pytest']\n"
        "    subprocess.run(['pytest', 'test_child.py::test_first'], cwd='child', env=env, check=True)\n"
        "    no_bytecode = [sys.executable, '-B', '-m', 'pytest']\n"
        "    subprocess.run([*no_bytecode, 'test_child.py::test_second'], cwd='child', env=env, check=True)\n"
        "    stock = [*command, '-o', 'addopts=']\n"
        "    stock_env = env.copy()\n"
        "    stock_env.pop('CODEX_RIG_PYTEST_ARTIFACTS')\n"
        "    subprocess.run([*stock, 'test_child.py::test_stock'], cwd='child', env=stock_env, check=True)\n"
        "    failed = subprocess.run([shutil.which('pytest'), '-o', 'addopts=', '--junit-xml=explicit.xml', 'test_child.py::test_explicit_failure'], cwd='child', env=env)\n"
        "    assert failed.returncode == 1\n"
        "    keys = ['PYTHONPATH', 'COVERAGE_FILE', 'CODEX_RIG_PYTEST_ARTIFACTS', 'PYTEST_ADDOPTS']\n"
        "    probe = f'import os; print(repr([os.getenv(k) for k in {keys!r}]))'\n"
        "    other = subprocess.check_output([sys.executable, '-c', probe], env=env, text=True)\n"
        "    assert other.strip() == repr([env.get(k) for k in keys])\n",
        encoding="utf-8",
    )
    run = project / "run with spaces"
    # Check restoration using pytest's in-process entry point before interpreter exit.
    driver = (
        "import pytest, subprocess, sys; original = subprocess.Popen.__init__; "
        f"result = pytest.main({['-q', '-p', 'no:xdist', *([] if parent_report else ['-o', 'addopts=']), 'test_outer.py']!r}); "
        "assert subprocess.Popen.__init__ is original; sys.exit(result)"
    )
    result = subprocess.run(
        [
            sys.executable,
            "-I",
            str(SHARED / "run_targeted_pytest.py"),
            "--checkout",
            str(project),
            str(run),
            "--",
            sys.executable,
            "-c",
            driver,
        ],
        env=os.environ
        | {
            "PYTEST_DISABLE_PLUGIN_AUTOLOAD": "1",
            "PYTEST_ADDOPTS": "",
            "CLEAR_CHILD_PATH": "yes" if clear_path else "no",
            "PATH": os.pathsep.join(
                (
                    str(Path(sysconfig.get_path("scripts")) / ".." / Path(sysconfig.get_path("scripts")).name),
                    os.environ["PATH"],
                )
            ),
            "PYTHONPATH": str(project / "parent-only-imports"),
            "PARENT_PATH": str(project / "parent-only-imports"),
        },
        capture_output=True,
        text=True,
        check=False,
    )
    assert result.returncode == 0, result.stdout + result.stderr
    assert (project / "results/report.xml").read_text(encoding="utf-8") == "prior report"
    assert (child / "existing.xml").read_text(encoding="utf-8") == "previous child report"
    assert (child / "explicit.xml").read_text(encoding="utf-8") == "previous CLI report"
    assert len(list(run.glob("pytest-child-*"))) == 3
    reports = [ElementTree.parse(path).getroot() for path in run.rglob("*.xml")]  # noqa: S314 - generated by fixture
    assert sorted(case.get("name") for report in reports for case in report.iter("testcase")) == [
        "test_explicit_failure",
        "test_first",
        *(["test_outer"] if parent_report else []),
        "test_second",
    ]
    assert (run / "junit.xml").is_file() is parent_report
