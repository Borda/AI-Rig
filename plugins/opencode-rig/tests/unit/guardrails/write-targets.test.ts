describe("write targets and remote command text", () => {
  it.each(COMMAND_CASES)("top level: %s", (command, ask) => {
    expect(decide(classifyCommand(command), "standard", GRANTED)?.effect).toBe(ask ? "ask" : undefined)
  })
  it.each(COMMAND_CASES)("saved script: %s", (command, _, ask) => {
    expect(decide(classifyCommand(persistedThenRun(command)), "standard", GRANTED)?.effect).toBe(
      ask ? "ask" : undefined,
    )
  })
})

describe.each(["top level", "saved script"])("write-targets guarded execution: %s", (scope) => {
  const wrap = (body: string) =>
    scope === "top level" ? body : `cat > x.sh <<'SAVED_END'\n${body}\nSAVED_END\nsh x.sh`
  it.each([
    "pre-commit install",
    "pre-commit install --hook-type pre-push",
    "pre-commit install-hooks",
    "husky",
    "husky init",
    "husky install",
    "lefthook install",
    "overcommit --install",
    "at -f x.sh now",
    "crontab x.txt",
    "launchctl load x.plist",
  ])("asks before loading options or executing guarded code: %s", (body) => {
    expect(decide(classifyCommand(wrap(body)), "standard", GRANTED)?.effect).toBe("ask")
  })
})
