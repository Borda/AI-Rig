"""Build the gitignored generated manifests a pytest session needs, then restore state.

Several collected modules read ``benchmarks/manifests/*.json`` at import time, so the build has to happen before
collection rather than in a fixture. ``benchmarks/conftest.py`` owns the hooks; this module owns the work so it stays
importable by its own tests.
"""

from __future__ import annotations

from collections.abc import Mapping, Sequence
from dataclasses import dataclass
from pathlib import Path
import subprocess
import sys

BENCHMARKS_DIR = Path(__file__).resolve().parent.parent
REPO_ROOT = BENCHMARKS_DIR.parent
# Dependency order: codex-agentic hashes codex-integration.json, and both Codex builders
# read provider-parity-methodology.json. Mirrors run-all.sh refresh_generated_manifests.
_MANIFEST_BUILDERS = (
    BENCHMARKS_DIR / "build-provider-parity-methodology-manifest.py",
    BENCHMARKS_DIR / "build-codex-integration-manifest.py",
    BENCHMARKS_DIR / "build-codex-agentic-manifest.py",
)
_GENERATED_MANIFEST_PATHS = (
    BENCHMARKS_DIR / "manifests" / "provider-parity-methodology.json",
    BENCHMARKS_DIR / "manifests" / "codex-integration.json",
    BENCHMARKS_DIR / "manifests" / "codex-integration.md",
    BENCHMARKS_DIR / "manifests" / "codex-agentic.json",
    BENCHMARKS_DIR / "manifests" / "codex-agentic.md",
)


@dataclass(frozen=True)
class GeneratedManifestArtifacts:
    """Paths made available by the deterministic manifest pre-collection build."""

    paths: tuple[Path, ...]
    initially_missing: tuple[Path, ...]
    generation_count: int
    build_error: str | None = None


def _generate_manifest_artifacts() -> None:
    """Generate the methodology, integration, and agentic manifests in dependency order."""
    for builder in _MANIFEST_BUILDERS:
        subprocess.run(
            [sys.executable, str(builder)],
            cwd=REPO_ROOT,
            check=True,
            capture_output=True,
            text=True,
        )


def _snapshot_manifests() -> dict[Path, bytes]:
    """Capture the bytes of every manifest that already existed before this session."""
    return {path: path.read_bytes() for path in _GENERATED_MANIFEST_PATHS if path.is_file()}


def _restore_manifests(snapshot: Mapping[Path, bytes], initially_missing: Sequence[Path]) -> None:
    """Return the checkout to its pre-session manifest state, bytes included.

    Deleting only the initially-absent outputs left every pre-existing manifest holding regenerated bytes, so a session
    silently rewrote tracked working-copy state.
    """
    for path, payload in snapshot.items():
        path.write_bytes(payload)
    for path in initially_missing:
        path.unlink(missing_ok=True)


def start_session(session) -> None:
    """Generate manifests before test-module imports require their JSON payloads.

    A builder failure is recorded rather than raised: aborting the whole session with a
    ``UsageError`` made an unrelated generator defect look like a total collection failure.
    ``test_generated_manifest_session.py`` asserts the successful build explicitly, so the
    failure still surfaces as one attributable test.

    Args:
        session: Active pytest session whose config carries the recorded artifacts.
    """
    workerinput = getattr(session.config, "workerinput", None)
    if workerinput is not None:
        generation_count, build_error = workerinput["generated_manifest_result"]
        session.config._generated_manifest_artifacts = GeneratedManifestArtifacts(
            paths=_GENERATED_MANIFEST_PATHS,
            initially_missing=(),
            generation_count=generation_count,
            build_error=build_error,
        )
        return

    initially_missing = tuple(path for path in _GENERATED_MANIFEST_PATHS if not path.exists())
    snapshot = _snapshot_manifests()
    session.config._generated_manifest_snapshot = snapshot
    session.config._generated_manifest_artifacts = GeneratedManifestArtifacts(
        paths=_GENERATED_MANIFEST_PATHS,
        initially_missing=initially_missing,
        generation_count=0,
    )
    build_error: str | None = None
    try:
        _generate_manifest_artifacts()
    except (subprocess.CalledProcessError, OSError) as exc:
        _restore_manifests(snapshot, initially_missing)
        stream_details = getattr(exc, "stderr", "") or getattr(exc, "stdout", "") or ""
        build_error = stream_details.strip() or str(exc)
    session.config._generated_manifest_artifacts = GeneratedManifestArtifacts(
        paths=_GENERATED_MANIFEST_PATHS,
        initially_missing=initially_missing,
        generation_count=0 if build_error else 1,
        build_error=build_error,
    )


def finish_session(session) -> None:
    """Restore the pre-session manifest state of an ignored checkout.

    Args:
        session: Active pytest session whose config carries the recorded artifacts.
    """
    if getattr(session.config, "workerinput", None) is not None:
        return
    artifacts = getattr(session.config, "_generated_manifest_artifacts", None)
    if artifacts is None:
        return
    _restore_manifests(getattr(session.config, "_generated_manifest_snapshot", {}), artifacts.initially_missing)
