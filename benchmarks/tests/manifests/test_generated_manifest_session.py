BENCHMARKS_DIR = Path(__file__).resolve().parent.parent.parent
REPO_ROOT = BENCHMARKS_DIR.parent

METHODOLOGY_BUILDER = "build-provider-parity-methodology-manifest.py"
INTEGRATION_BUILDER = "build-codex-integration-manifest.py"
AGENTIC_BUILDER = "build-codex-agentic-manifest.py"


def _publish_with_builder(builder_name: str) -> Callable[[Path, bytes], None]:
    """Return a publisher that writes through the named builder script's own `_write_or_check`."""

    def _publish(output: Path, payload: bytes) -> None:
        runpy.run_path(str(BENCHMARKS_DIR / builder_name))["_write_or_check"](output, payload, check=False)

    return _publish


def _publish_with_session_restore(output: Path, payload: bytes) -> None:
    """Publish *payload* through the session's manifest restore path."""
    manifest_session._restore_manifests({output: payload}, ())


@pytest.fixture
def observed_manifest_writes(tmp_path: Path, monkeypatch: pytest.MonkeyPatch) -> SimpleNamespace:
    """Record the on-disk bytes of `manifest.json` at the instant each binary write is about to land.

    Real file I/O is kept: only `io.open` is wrapped so a `wb` stream reports what a concurrent reader would see just
    before the payload is written. Exposes `output`, `previous`, `replacement`, and `observed`.
    """
    output = tmp_path / "manifest.json"
    previous = b'{"generation": "previous"}\n'
    output.write_bytes(previous)
    observed: list[bytes] = []
    real_open = io.open

    class ObservedWriter:
        """Keep real file I/O while exposing the moment immediately before the bytes are written."""

        def __init__(self, stream: Any) -> None:
            self.stream = stream

        def __enter__(self) -> Any:
            return self

        def __exit__(self, *args: Any) -> None:
            self.stream.close()

        def __getattr__(self, name: str) -> Any:
            return getattr(self.stream, name)

        def write(self, payload: bytes) -> int:
            observed.append(output.read_bytes())
            return self.stream.write(payload)

    def observe_open(file: Any, mode: str = "r", *args: Any, **kwargs: Any) -> Any:
        stream = real_open(file, mode, *args, **kwargs)
        return ObservedWriter(stream) if mode == "wb" else stream

    monkeypatch.setattr(io, "open", observe_open)
    return SimpleNamespace(
        output=output, previous=previous, replacement=b'{"generation": "replacement"}\n', observed=observed
    )


class TestManifestSession:
    """Session-level generation, reuse by xdist workers, and cleanup of the generated manifest chain."""

    @pytest.mark.integration
    @pytest.mark.parametrize("builder", [METHODOLOGY_BUILDER, INTEGRATION_BUILDER, AGENTIC_BUILDER])
    def test_makes_manifests_ready_once_with_byte_stable_outputs(
        self, generated_manifest_artifacts: Any, builder: str
    ) -> None:
        """Session generation must make every manifest available and satisfy read-only checks.

        The session builds the whole chain once; each builder's real `--check` run then confirms the generated bytes are
        exactly what that builder would produce, so collection never sees a stale or missing manifest.
        """
        artifacts = generated_manifest_artifacts

        result = subprocess.run(
            [sys.executable, str(BENCHMARKS_DIR / builder), "--check"],
            cwd=REPO_ROOT,
            check=False,
            capture_output=True,
            text=True,
        )

        assert artifacts.generation_count == 1
        assert all(path.is_file() for path in artifacts.paths)
        assert result.returncode == 0, result.stderr

    def test_hook_recreates_only_absent_outputs_and_cleans_them(
        self, tmp_path: Path, monkeypatch: pytest.MonkeyPatch
    ) -> None:
        """A clean checkout must build the chain once, then leave no generated outputs behind.

        All five outputs start absent. Starting the session runs the three builders in order and materializes the files;
        finishing the session removes every file the session itself created.
        """
        outputs = tuple(
            tmp_path / name
            for name in ("methodology.json", "integration.json", "integration.md", "agentic.json", "agentic.md")
        )
        builders = tuple(tmp_path / name for name in ("methodology.py", "integration.py", "agentic.py"))
        calls: list[tuple[str, ...]] = []

        def _fake_run(command: list[str], **_: object) -> subprocess.CompletedProcess[str]:
            """Record the dependency chain and materialize its final generated files."""
            calls.append(tuple(command))
            if len(calls) == len(builders):
                for path in outputs:
                    path.write_text(path.name, encoding="utf-8")
            return subprocess.CompletedProcess(command, 0, "", "")

        monkeypatch.setattr(manifest_session, "_GENERATED_MANIFEST_PATHS", outputs)
        monkeypatch.setattr(manifest_session, "_MANIFEST_BUILDERS", builders)
        monkeypatch.setattr(subprocess, "run", _fake_run)
        session = SimpleNamespace(config=SimpleNamespace())

        manifest_session.start_session(session)

        artifacts = session.config._generated_manifest_artifacts
        assert artifacts.initially_missing == outputs
        assert artifacts.generation_count == 1
        assert calls == [(sys.executable, str(builder)) for builder in builders]
        assert all(path.is_file() for path in outputs)

        manifest_session.finish_session(session)

        assert not any(path.exists() for path in outputs)

    @pytest.mark.parametrize(
        ("generation_count", "build_error"),
        [pytest.param(1, None, id="successful-build"), pytest.param(0, "builder failed", id="failed-build")],
    )
    def test_xdist_worker_reuses_controller_result_without_rebuilding_or_restoring(
        self, tmp_path: Path, monkeypatch: pytest.MonkeyPatch, generation_count: int, build_error: str | None
    ) -> None:
        """A worker must leave the controller's shared manifest files untouched.

        An xdist worker receives the controller's generation result in `workerinput`; it adopts that result as is and
        neither starts its own build nor restores or deletes the controller's files when it finishes.
        """
        output = tmp_path / "methodology.json"
        output.write_text("controller output", encoding="utf-8")
        rebuild = mock.create_autospec(manifest_session._generate_manifest_artifacts)
        monkeypatch.setattr(manifest_session, "_GENERATED_MANIFEST_PATHS", (output,))
        monkeypatch.setattr(manifest_session, "_generate_manifest_artifacts", rebuild)
        session = SimpleNamespace(
            config=SimpleNamespace(workerinput={"generated_manifest_result": (generation_count, build_error)})
        )

        manifest_session.start_session(session)
        artifacts = session.config._generated_manifest_artifacts
        manifest_session.finish_session(session)

        assert artifacts.generation_count == generation_count
        assert artifacts.build_error == build_error
        rebuild.assert_not_called()
        assert output.read_text(encoding="utf-8") == "controller output"


class TestManifestPublication:
    """Atomic publication of generated manifest bytes: no truncated reads, no stray staging files."""

    @pytest.mark.parametrize(
        "publish",
        [
            pytest.param(_publish_with_builder(METHODOLOGY_BUILDER), id="methodology"),
            pytest.param(_publish_with_builder(INTEGRATION_BUILDER), id="integration"),
            pytest.param(_publish_with_builder(AGENTIC_BUILDER), id="agentic"),
            pytest.param(_publish_with_session_restore, id="session-restore"),
        ],
    )
    def test_readers_never_observe_a_truncated_publication(
        self, tmp_path: Path, observed_manifest_writes: SimpleNamespace, publish: Callable[[Path, bytes], None]
    ) -> None:
        """Read at the write boundary that nested pytest sessions can overlap with launcher readers.

        Each writer replaces an existing manifest; at every moment bytes are written, the visible target must still be
        the complete previous generation, and the final file must be the full replacement with no staging leftovers.
        """
        writes = observed_manifest_writes

        publish(writes.output, writes.replacement)

        assert writes.observed
        assert all(payload == writes.previous for payload in writes.observed)
        assert json.loads(writes.output.read_bytes()) == {"generation": "replacement"}
        assert list(tmp_path.iterdir()) == [writes.output]

    def test_failed_publication_preserves_bytes_and_removes_temporary_file(
        self, tmp_path: Path, monkeypatch: pytest.MonkeyPatch
    ) -> None:
        """A failed rename must neither truncate the old manifest nor leave a stray staging file.

        The final `os.replace` is made to fail after the staged bytes are complete; the previous manifest must remain
        byte-identical and the directory must contain only the manifest.
        """
        output = tmp_path / "manifest.json"
        output.write_bytes(b'{"generation":"previous"}')

        def fail_replace(source: Path, destination: Path) -> None:
            assert source.parent == destination.parent == tmp_path
            assert source.read_bytes() == b'{"generation":"replacement"}'
            assert destination.read_bytes() == b'{"generation":"previous"}'
            raise PermissionError("publication denied")

        monkeypatch.setattr(manifest_io.os, "replace", fail_replace)

        with pytest.raises(PermissionError, match="publication denied"):
            manifest_io.write_manifest_bytes(output, b'{"generation":"replacement"}')

        assert output.read_bytes() == b'{"generation":"previous"}'
        assert list(tmp_path.iterdir()) == [output]

    def test_identical_bytes_do_not_republish(self, tmp_path: Path, monkeypatch: pytest.MonkeyPatch) -> None:
        """Nested collection sessions must avoid replacing already-current generated coordinates.

        A manifest already holding the exact payload is left alone: no rename happens, so a concurrent reader never
        races a pointless replacement.
        """
        output = tmp_path / "manifest.json"
        payload = b'{"generation":"same"}'
        manifest_io.write_manifest_bytes(output, payload)
        replace = mock.create_autospec(os.replace)
        monkeypatch.setattr(manifest_io.os, "replace", replace)

        manifest_io.write_manifest_bytes(output, payload)

        replace.assert_not_called()
        assert output.read_bytes() == payload
        assert list(tmp_path.iterdir()) == [output]
